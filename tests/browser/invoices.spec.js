import {test, expect} from '@playwright/test';
test('create an invoice and convert a quote without duplicates', async ({page}) => {
  await page.goto('/login');
  await page.getByLabel('Email',{exact:true}).fill('office@example.test');
  await page.getByLabel('Password',{exact:true}).fill('Browser-test-password-123');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Overview',exact:true})).toBeVisible();
  const session = await (await page.request.get('/api/session')).json();
  const headers = {Origin:'http://localhost:3101','X-CSRF-Token':session.csrf};
  const cResponse = await page.request.post('/api/records/contacts',{headers,data:{name:'Invoice browser customer'}});
  expect(cResponse.ok()).toBeTruthy();
  const c = await cResponse.json();
  await page.getByRole('link',{name:'Invoices',exact:true}).click();
  await page.getByRole('link',{name:'+ New invoice',exact:true}).click();
  await page.getByLabel('Name / reference',{exact:true}).fill('Manual browser invoice');
  await page.getByLabel('Contact',{exact:true}).selectOption(String(c.id));
  await page.getByLabel('Total (AUD)',{exact:true}).fill('125.50');
  await page.getByLabel('Work description',{exact:true}).fill('Concrete repair');
  await page.getByLabel('Due date',{exact:true}).fill('2026-11-01');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(page).toHaveURL(/\/office\/invoices\/\d+$/);
  await page.getByLabel('Invoice status',{exact:true}).selectOption('issued');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(page.getByLabel('Total (AUD)',{exact:true})).toBeDisabled();
  await page.getByLabel('Invoice status',{exact:true}).selectOption('paid');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(page.getByText('Changes saved.',{exact:true})).toBeVisible();
  const qResponse = await page.request.post('/api/records/quotes',{headers,data:{name:'Conversion browser quote',contact_id:c.id,amount_cents:98050,scope:'Driveway concrete',exclusions:'Excavation'}});
  expect(qResponse.ok()).toBeTruthy();
  const q = await qResponse.json();
  await page.goto('/office/quotes/'+q.id);
  await page.getByRole('button',{name:'Convert to invoice',exact:true}).click();
  await expect(page).toHaveURL(/\/office\/invoices\/\d+$/);
  const invoiceURL = page.url();
  await expect(page.getByLabel('Total (AUD)',{exact:true})).toHaveValue('980.50');
  await expect(page.getByLabel('Work description',{exact:true})).toHaveValue('Driveway concrete');
  await expect(page.getByLabel('Invoice status',{exact:true})).toHaveValue('draft');
  await page.getByRole('link',{name:'Source quote #'+q.id,exact:true}).click();
  await page.getByRole('button',{name:'Convert to invoice',exact:true}).click();
  await expect(page).toHaveURL(invoiceURL);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1)).toBeTruthy();
});
